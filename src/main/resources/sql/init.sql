BEGIN;

CREATE TABLE IF NOT EXISTS PUBLIC.USERS (
	USER_ID UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
	EMAIL VARCHAR NOT NULL UNIQUE,
	PASSWORD VARCHAR NOT NULL,
	ROLE VARCHAR NOT NULL CHECK (ROLE IN ('customer', 'salesperson')),
	NAME VARCHAR NOT NULL,
	ADDRESS VARCHAR,
	ZIP INTEGER,
	PHONE VARCHAR
);

CREATE TABLE IF NOT EXISTS PUBLIC.ORDERS (
	ORDER_ID UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
	CUSTOMER_ID UUID NOT NULL REFERENCES PUBLIC.USERS (USER_ID),
	SALESPERSON_ID UUID REFERENCES PUBLIC.USERS (USER_ID),
	WIDTH INTEGER NOT NULL, -- cm
	LENGTH INTEGER NOT NULL, -- cm
	SHED_WIDTH INTEGER, -- cm, NULL = no shed
	SHED_LENGTH INTEGER, -- cm
	STATUS VARCHAR NOT NULL DEFAULT 'request' CHECK (
		STATUS IN ('request', 'offer_sent', 'paid', 'delivered')
	),
	SALES_PRICE NUMERIC(10, 2),
	CREATION_DATE TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS PUBLIC.MATERIALS (
	MATERIAL_ID UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
	NAME VARCHAR NOT NULL,
	UNIT VARCHAR NOT NULL,
	LENGTH INTEGER NOT NULL, -- cm
	PRICE NUMERIC(10, 2) NOT NULL
);

CREATE TABLE IF NOT EXISTS PUBLIC.ORDER_LINES (
	ORDER_LINE_ID UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
	ORDER_ID UUID NOT NULL REFERENCES PUBLIC.ORDERS (ORDER_ID) ON DELETE CASCADE,
	MATERIAL_ID UUID NOT NULL REFERENCES PUBLIC.MATERIALS (MATERIAL_ID),
	QUANTITY INTEGER NOT NULL,
	DESCRIPTION VARCHAR NOT NULL
);

END;
